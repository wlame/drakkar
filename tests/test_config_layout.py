"""The config tree, leaf by leaf, in the documented order.

The list below is the layout an operator writes, section by section, as the
config reference documents it. ``*`` stands for an operator-chosen name (a
connection, a sink instance, a Mongo statement) and ``[]`` for an element of a
list of objects. A key that is added, renamed or moved changes this list.
"""

