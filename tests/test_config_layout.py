# The policy keys every sink instance takes on top of its own keys; a key not
# given reads sinks.defaults.
SINK_POLICY_KEYS = ('on_failure', 'max_retries', 'delivery_timeout', 'breaker_failures', 'breaker_cooldown')
RESILIENCE_KEYS = ('timeout', 'max_retries', 'backoff', 'max_backoff', 'breaker_failures', 'breaker_cooldown')


def _sink(sink_type: str, *keys: str) -> list[str]:
    return [f'sinks.{sink_type}.*.{key}' for key in (*SINK_POLICY_KEYS, 'depends_on', *keys)]


def _resilience(section: str) -> list[str]:
    return [f'{section}.resilience.{key}' for key in RESILIENCE_KEYS]


